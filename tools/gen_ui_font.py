#!/usr/bin/env python3
"""Generate main/ui_font.h: a 16x16 1-bit bitmap subset for the UI strings."""
from pathlib import Path
import re
import sys

from PIL import Image, ImageDraw, ImageFont

PROJECT = Path(__file__).resolve().parents[1]
OUT = PROJECT / "main" / "ui_font.h"
FONT_CANDIDATES = [
    r"C:\Windows\Fonts\simhei.ttf",
    r"C:\Windows\Fonts\msyhbd.ttc",
    r"C:\Windows\Fonts\msyh.ttc",
]
CELL = 16
THRESHOLD = 96

def ui_characters():
    # Read the authored C UI instead of maintaining a second narrative copy.
    source = (PROJECT / "main" / "game_view.c").read_text(encoding="utf-8")
    strings = re.findall(r'"(?:\\.|[^"\\])*"', source)
    return sorted({ch for value in strings for ch in value if ord(ch) > 0x7F})



def main():
    chars = ui_characters()
    font_path = next((p for p in FONT_CANDIDATES if Path(p).exists()), None)
    if not font_path:
        print("no CJK font found", file=sys.stderr)
        return 1
    font = ImageFont.truetype(font_path, CELL)
    glyphs = []
    for ch in chars:
        image = Image.new("L", (CELL, CELL), 0)
        draw = ImageDraw.Draw(image)
        box = draw.textbbox((0, 0), ch, font=font)
        width = box[2] - box[0]
        height = box[3] - box[1]
        x = (CELL - width) // 2 - box[0]
        y = (CELL - height) // 2 - box[1]
        draw.text((x, y), ch, font=font, fill=255)
        rows = []
        for yy in range(CELL):
            lo = hi = 0
            for xx in range(8):
                if image.getpixel((xx, yy)) >= THRESHOLD:
                    lo |= 1 << (7 - xx)
            for xx in range(8, 16):
                if image.getpixel((xx, yy)) >= THRESHOLD:
                    hi |= 1 << (15 - xx)
            rows.extend((lo, hi))
        glyphs.append((ord(ch), rows))

    lines = [
        "/* Generated by tools/gen_ui_font.py from %s. Do not edit. */" % Path(font_path).name,
        "#ifndef UI_FONT_H",
        "#define UI_FONT_H",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    uint32_t codepoint;",
        "    uint8_t bitmap[32]; /* 16 rows, 2 bytes each, MSB first */",
        "} ui_glyph_t;",
        "",
        "static const ui_glyph_t ui_glyphs[] = {",
    ]
    for codepoint, rows in glyphs:
        values = ",".join(str(v) for v in rows)
        lines.append("    {0x%04X, {%s}}," % (codepoint, values))
    lines += [
        "};",
        "",
        "#define UI_GLYPH_COUNT (sizeof(ui_glyphs) / sizeof(ui_glyphs[0]))",
        "",
        "#endif",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"font: {Path(font_path).name}, glyphs: {len(glyphs)}, "
          f"bytes: {OUT.stat().st_size}")
    print("chars:", "".join(chars))
    return 0


if __name__ == "__main__":
    sys.exit(main())
