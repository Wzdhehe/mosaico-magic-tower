#!/usr/bin/env python3
"""Encode designer-owned SCORES. No runtime samples or composition.

Title tables are the unchanged original project title; all campaign pitches,
rhythms, phrase forms, tempi and chords come from campaign_content.py.
"""
import argparse
import importlib.util
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets_src/level_design/campaign_content.py"
OUTPUT = ROOT / "main/game_music_score.h"
TRACK_KEYS = ("gate", "water", "forge", "court", "crown", "king", "home", "victory", "fallen")


def midi(pitch):
    if pitch == "R":
        return 0
    match = re.fullmatch(r"([A-G])([bs]?)([0-8])", pitch)
    if not match:
        raise ValueError(f"Invalid authored pitch: {pitch}")
    note, accidental, octave = match.groups()
    return 12 * (int(octave) + 1) + dict(C=0, D=2, E=4, F=5, G=7, A=9, B=11)[note] + {"": 0, "b": -1, "s": 1}[accidental]


def phrase(text):
    result = []
    for token in text.split():
        pitch, length = token.split(":")
        length = int(length)
        if length < 1:
            raise ValueError("Non-positive authored duration")
        result += [midi(pitch)] + [255] * (length - 1)
    if len(result) != 32:
        raise ValueError(f"Expected 32 sixteenths, got {len(result)}: {text}")
    return result


def triad(symbol):
    match = re.fullmatch(r"([A-G][bs]?)(m?)", symbol)
    if not match:
        raise ValueError(f"Unsupported authored chord: {symbol}")
    root = midi(match[1] + "3")
    return [root, root + (3 if match[2] else 4), root + 7]


def table(kind, name, rows, dimensions, suffix=""):
    lines = [f"static const {kind} {name}{dimensions}={{"]
    for row in rows:
        if isinstance(row[0], list):
            lines.append(" {" + ",".join("{" + ",".join(map(str, v)) + "}" for v in row) + "},")
        else:
            lines.append(" {")
            for start in range(0, len(row), 16):
                lines.append("  " + ",".join(str(v) + suffix for v in row[start:start + 16]) + ",")
            lines.append(" },")
    return "\n".join(lines + ["};\n"])


def generate():
    spec = importlib.util.spec_from_file_location("campaign_music_source", SOURCE)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    scores = module.SCORES
    leads, basses, chords = [TITLE_LEAD], [], [TITLE_CHORDS]
    rhythm = [1, 255, 0, 2, 1, 255, 2, 0]
    basses.append([255 if n == 255 else 0 if n == 0 else chord[0] + 12 + (7 if n == 2 else 0)
                   for chord in TITLE_CHORDS for n in rhythm])
    units = [7500]
    for key in TRACK_KEYS:
        score = scores[key]
        if score["form"] != ["lead", "lead", "answer", "lead"] or score["chord_span_sixteenths"] != 32 or len(score["chords"]) != 4:
            raise ValueError(f"Unexpected authored form for {key}")
        leads.append(sum((phrase(score[section]) for section in score["form"]), []))
        basses.append(phrase(score["bass"]) * 4)
        chords.append([triad(chord) for chord in score["chords"]] + [[0, 0, 0]] * 12)
        units.append(round(24000 * 60 / (score["bpm"] * 4)))
    triangle = [round(26755 * (1 - abs(((i + 64) % 256) / 64 - 2))) for i in range(256)]
    # Offline soft 25% pulse, three harmonics; runtime uses one lookup.
    pulse = [sum(2 * math.sin(math.pi * n / 4) / (math.pi * n) * math.cos(2 * math.pi * n * (i / 256 - .125))
                 for n in range(1, 4)) for i in range(256)]
    pulse = [round(v * 26755 / max(abs(x) for x in pulse)) for v in pulse]
    # Integer rounding may introduce a fraction of a sample of DC; cancel it.
    pulse[0] -= sum(pulse)
    increments = [round(440 * 2 ** ((n - 69) / 12) * 2 ** 32 / 24000) for n in range(128)]
    out = "// SPDX-License-Identifier: MIT\n// Generated by tools/gen_campaign_music.py from designer-owned SCORES.\n// 0 = rest, 255 = tie; title uses eighths, campaign uses sixteenths.\n#pragma once\n"
    count=1+len(TRACK_KEYS)
    out += table("uint8_t", "melody", leads, f"[{count}][128]")
    out += table("uint8_t", "bass_notes", basses, f"[{count}][128]")
    out += "/* Standard root/third/fifth; two harmony voices use third and fifth. */\n"
    out += table("uint8_t", "chords", chords, f"[{count}][16][3]")
    out += f"static const uint16_t unit_frames[{count}]={{" + ",".join(map(str, units)) + "};\n"
    out += "static const uint8_t chord_span[10]={8,32,32,32,32,32,32,32,32,32};\n"
    out += "static const uint8_t lead_wave[10]={0,1,1,2,1,1,2,1,1,0};\n"
    out += table("uint16_t", "voice_gain", [[3000, 560, 460, 1850]] + [[2700, 440, 380, 1800]] * 7 + [[2700,520,440,1700],[1800,320,280,1250]], f"[{count}][4]")
    out += 'static const char *const track_names[10]={"Lantern at the Gate","Broken Gate","Sunken Hall","Ash Works","Silent Court","Star Crown","King","Home","Dawn above the Tower","One More Lantern"};\n'
    out += table("int16_t", "waveform", [TITLE_WAVE, triangle, pulse], "[3][256]")
    out += table("uint32_t", "note_increment", [increments], "[1][128]", "U")
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated score is stale")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("Campaign score is stale; run python tools/gen_campaign_music.py")
        print("PASS: campaign music header matches authored SCORES")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
        print(f"Generated {OUTPUT}")

